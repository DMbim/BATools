        public PostableCommandInterceptor(UIApplication uiApp, TelemetryService telemetryService)
        {
            _uiApp = uiApp ?? throw new ArgumentNullException(nameof(uiApp));
            _telemetryService = telemetryService ?? throw new ArgumentNullException(nameof(telemetryService));
        }

        public void Register()
        {
            foreach (PostableCommand command in TrackedCommands)
            {
                try
                {
                    RevitCommandId commandId = RevitCommandId.LookupPostableCommandId(command);

                    if (commandId == null)
                        continue;

                    AddInCommandBinding binding = _uiApp.CreateAddInCommandBinding(commandId); // <- FIXED: removed CanAdd guard
                    binding.BeforeExecuted += (sender, args) => OnCommandBeforeExecuted(command);

                    _bindings[command] = binding; // Strong reference — prevents GC dropping the handler
                }
                catch (Exception ex)
                {
                    // Binding may already exist from another add-in — skip silently
                    System.Diagnostics.Debug.WriteLine(
                        $"[BA.Telemetry] Failed to bind PostableCommand.{command}: {ex.Message}");
                }
            }
        }

        public void Unregister()
        {
            foreach (var kvp in _bindings)
            {
                try
                {
                    RevitCommandId commandId = RevitCommandId.LookupPostableCommandId(kvp.Key);

                    if (commandId == null)
                        continue;

                    _uiApp.RemoveAddInCommandBinding(commandId); // <- FIXED: removed CanRemove guard
                }
                catch (Exception ex)
                {
                    System.Diagnostics.Debug.WriteLine(
                        $"[BA.Telemetry] Failed to unbind PostableCommand.{kvp.Key}: {ex.Message}");
                }
            }

            _bindings.Clear();
        }

        private void OnCommandBeforeExecuted(PostableCommand command)
        {
            try
            {
                Document activeDoc = null;

                try
                {
                    activeDoc = _uiApp.ActiveUIDocument?.Document;
                }
                catch { }

                _telemetryService.LogCommandExecuted(
                    commandName: command.ToString(),
                    executionMethod: "PostableCommand",
                    document: activeDoc
                );
            }
            catch { }
        }

        public void Dispose()
        {
            Unregister();
        }
    }
